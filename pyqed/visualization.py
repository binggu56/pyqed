"""Browser and notebook visualization helpers.

The public :func:`view` function builds a small, serializable scene rather
than tying Python to a particular JavaScript renderer.  Geometry-only scenes
retain the compact URL-fragment protocol used by older versions of the
viewer.  Volumetric scenes are sent with ``postMessage`` from a local launcher
so potentially large orbital and density arrays never appear in a URL.
"""

