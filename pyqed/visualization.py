import numpy as np

from pyqed.units import au2angstrom, au2wavenumber


_VIEWER_URL = "https://pyqed.org/viewer"
_VIEWER_ORIGIN = "https://pyqed.org"
_SCENE_KIND = "pyqed-scene"
_SCENE_VERSION = 1
_MAX_ATOMS = 500
_MAX_FIELDS = 512
_MAX_AXIS_SIZE = 2048
_MAX_FIELD_POINTS = 2_000_000
_MAX_SCENE_POINTS = 8_000_000
_MAX_SERIALIZED_BYTES = 64_000_000
_MAX_CUBE_BYTES = 80_000_000
_MAX_GEOMETRY_CHARS = 1_000_000
_MAX_FLOAT32 = float(np.finfo(np.float32).max)
_COLOR_PATTERN = re.compile(
    r"^(?:#[0-9a-f]{3}|#[0-9a-f]{6}|#[0-9a-f]{8}|[a-z][a-z0-9_-]{0,31})$",
    re.IGNORECASE,
)
_SIGNED_FIELD_KINDS = {
    "orbital",
    "spin-density",
    "difference-density",
    "transition-density",
    "esp",
    "generic",
}
_FIELD_KINDS = _SIGNED_FIELD_KINDS | {"electron-density"}
_REPRESENTATIONS = {
    "ball-stick": "ball-stick",
    "ball_and_stick": "ball-stick",
    "ball-and-stick": "ball-stick",
    "space-fill": "space-fill",
    "space_filling": "space-fill",
    "space-filling": "space-fill",
    "wireframe": "wireframe",
}
def _normalize_representation(value: str) -> str:
    try:
        return _REPRESENTATIONS[str(value).lower()]
    except KeyError as exc:
        choices = "ball-stick, space-fill, or wireframe"
        raise ValueError(f"representation must be {choices}") from exc


def _atom_symbols(molecule) -> list[str]:
    method = getattr(molecule, "atom_symbols", None)
    if callable(method):
        return list(method())
    natom = getattr(molecule, "natom", getattr(molecule, "natm", None))
    atom_symbol = getattr(molecule, "atom_symbol", None)
    if natom is not None and callable(atom_symbol):
        return [atom_symbol(i) for i in range(int(natom))]
    raise TypeError("molecule must provide atom_symbols() or atom_symbol(index)")


def _molecule_xyz(molecule, *, coordinates_unit: str) -> str:
    try:
        symbols = _atom_symbols(molecule)
        coordinates = np.asarray(molecule.atom_coords(), dtype=float)
    except AttributeError as exc:
        raise TypeError(
            "view() expects a molecule or an object with a .mol reference"
        ) from exc

    if coordinates.shape != (len(symbols), 3):
        raise ValueError(
            "atom_coords() must return an array with shape (number of atoms, 3)"
        )
    if not symbols:
        raise ValueError("cannot view a molecule with no atoms")
    if len(symbols) > _MAX_ATOMS:
        raise ValueError(f"the viewer supports at most {_MAX_ATOMS} atoms")
    if not np.all(np.isfinite(coordinates)):
        raise ValueError("molecular coordinates must be finite")

    unit = str(coordinates_unit).lower()
    if unit in {"bohr", "b", "au", "a.u."}:
        coordinates = coordinates * au2angstrom
    elif unit not in {"angstrom", "angstroms", "a", "å"}:
        raise ValueError("coordinates_unit must be 'bohr' or 'angstrom'")

    rows = [str(len(symbols)), "Generated by PyQED, coordinates in angstrom"]
    for symbol, (x, y, z) in zip(symbols, coordinates):
        symbol = str(symbol).strip()
        symbol = symbol[:1].upper() + symbol[1:].lower()
        if symbol not in _ELEMENT_SET:
            raise ValueError(f"invalid atomic symbol: {symbol!r}")
        if np.max(np.abs((x, y, z))) > _MAX_FLOAT32:
            raise ValueError("molecular coordinates exceed the viewer's numeric range")
        rows.append(f"{symbol:<3} {x: .10f} {y: .10f} {z: .10f}")
    return "\n".join(rows)


def _validate_xyz_payload(xyz: str) -> str:
    if not isinstance(xyz, str):
        raise TypeError("xyz must be text")
    if not xyz.strip():
        raise ValueError("xyz cannot be empty")
    if len(xyz) > _MAX_GEOMETRY_CHARS:
        raise ValueError("xyz must be smaller than 1 MB")

    raw_lines = [line.strip() for line in xyz.strip().splitlines()]
    first_is_count = bool(raw_lines and raw_lines[0].isdigit())
    if first_is_count:
        expected = int(raw_lines[0])
        coordinate_lines = raw_lines[2:]
    else:
        expected = None
        coordinate_lines = [
            row.strip()
            for line in raw_lines
            for row in line.split(";")
            if row.strip()
        ]

    atoms = 0
    for line in coordinate_lines:
        if not line:
            continue
        fields = re.split(r"[\s,]+", line)
        if len(fields) != 4:
            raise ValueError("each XYZ row must contain an element and three coordinates")
        symbol = fields[0][:1].upper() + fields[0][1:].lower()
        if symbol not in _ELEMENT_SET:
            raise ValueError(f"invalid atomic symbol: {fields[0]!r}")
        try:
            coordinates = [float(value.replace("D", "E").replace("d", "e")) for value in fields[1:]]
        except ValueError as exc:
            raise ValueError("XYZ coordinates must be numeric") from exc
        if not all(np.isfinite(value) and abs(value) <= _MAX_FLOAT32 for value in coordinates):
            raise ValueError("XYZ coordinates exceed the viewer's numeric range")
        atoms += 1

    if atoms == 0:
        raise ValueError("xyz must contain at least one atom")
    if atoms > _MAX_ATOMS:
        raise ValueError(f"the viewer supports at most {_MAX_ATOMS} atoms")
    if expected is not None and expected != atoms:
        raise ValueError(f"XYZ header declares {expected} atoms, but {atoms} were found")
    return xyz


def _xyz_from_arrays(symbols, coordinates_angstrom) -> str:
    class _ArrayMolecule:
        def atom_symbols(self):
            return symbols

        def atom_coords(self):
            return coordinates_angstrom

    return _molecule_xyz(_ArrayMolecule(), coordinates_unit="angstrom")


