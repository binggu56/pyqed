def _evaluate_ao(reference, points) -> np.ndarray:
    molecule = reference.mol
    eval_gto = getattr(molecule, "eval_gto", None)
    if callable(eval_gto):
        name = "GTOval_cart" if bool(getattr(molecule, "cart", False)) else "GTOval_sph"
        values = np.asarray(eval_gto(name, points))
        if values.ndim != 2:
            raise ValueError("molecule.eval_gto() did not return a 2-D AO array")
        return values.T

    analysis = None
    if callable(getattr(reference, "analyze", None)):
        try:
            candidate = reference.analyze()
        except TypeError:
            candidate = None
        if callable(getattr(candidate, "_evaluate_ao_values", None)):
            analysis = candidate
    if analysis is None:
        from pyqed.qchem.hf.analysis import RHFAnalysis

        analysis = RHFAnalysis(reference)
    return np.asarray(
        analysis._evaluate_ao_values(points, screen_basis=True, tol_screen=1.0e-8)
    )


def _grid_geometry(cube) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    origin_bohr = np.asarray(cube.origin, dtype=float)
    axes_bohr = np.diag(np.asarray(cube.spacing, dtype=float))
    return cube.get_coords(), origin_bohr * au2angstrom, axes_bohr * au2angstrom


def _spin_arrays(reference, attribute: str) -> tuple[np.ndarray, ...]:
    value = getattr(reference, attribute, None)
    if value is None:
        raise ValueError(f"SCF object has no {attribute}; run the calculation first")
    if isinstance(value, (tuple, list)) and len(value) == 2:
        return tuple(np.asarray(item) for item in value)
    array = np.asarray(value)
    if array.ndim >= 2 and array.shape[0] == 2 and attribute != "mo_coeff":
        return (array[0], array[1])
    if attribute == "mo_coeff" and array.ndim == 3 and array.shape[0] == 2:
        return (array[0], array[1])
    return (array,)


def _frontier_index(occupations, selector: str) -> int:
    occ = np.asarray(occupations, dtype=float)
    occupied = np.flatnonzero(occ > 1.0e-8)
    virtual = np.flatnonzero(occ <= 1.0e-8)
    key = selector.strip().lower().replace("_", "").replace(" ", "")
    if key.startswith("homo"):
        if occupied.size == 0:
            raise ValueError("HOMO requires at least one occupied orbital")
        base = int(occupied[-1])
        suffix = key[4:]
    elif key.startswith("lumo"):
        if virtual.size == 0:
            raise ValueError("LUMO requires at least one virtual orbital")
        base = int(virtual[0])
        suffix = key[4:]
    else:
        raise ValueError(f"unknown orbital selector {selector!r}")
    if suffix:
        try:
            base += int(suffix)
        except ValueError as exc:
            raise ValueError(f"invalid frontier-orbital offset in {selector!r}") from exc
    return base


def _orbital_indices(selector, occupations, nmo: int) -> list[tuple[int, str]]:
    if isinstance(selector, str):
        key = selector.strip().lower()
        if key == "all":
            requested = list(range(nmo))
        else:
            requested = [selector]
    elif np.isscalar(selector):
        requested = [selector]
    else:
        requested = list(selector)
        if not requested:
            raise ValueError("orbital selector list cannot be empty")

    result = []
    for item in requested:
        if isinstance(item, str):
            index = _frontier_index(occupations, item)
            label = item.strip().upper()
        else:
            if isinstance(item, (bool, np.bool_)):
                raise TypeError("boolean values are not orbital indices")
            index = int(item)
            if index != item:
                raise TypeError("orbital indices must be integers")
            label = f"MO {index + 1}"
        if index < 0 or index >= nmo:
            raise IndexError(f"orbital index {index} is outside [0, {nmo})")
        result.append((index, label))
    return result


def _field_values(coeff, ao_values, shape, *, name):
    if coeff.shape != (ao_values.shape[0],):
        raise ValueError(
            f"{name} coefficient length {coeff.shape[0]} does not match AO dimension "
            f"{ao_values.shape[0]}"
        )
    return _real_array(coeff.conj() @ ao_values, name=name).reshape(shape)


def _orbital_fields(
    reference,
    selector,
    *,
    coeff,
    orbital_spin,
    ao_values,
    shape,
    origin,
    axes,
    isovalues,
    opacity,
) -> list[ScalarField3D]:
    coefficients = _spin_arrays(reference, "mo_coeff")
    occupations = _spin_arrays(reference, "mo_occ")
    energies = _spin_arrays(reference, "mo_energy") if getattr(reference, "mo_energy", None) is not None else ()

    if coeff is not None and selector is not None:
        raise ValueError("provide orbital selectors or coeff, not both")
    custom = coeff
    if custom is None and isinstance(selector, np.ndarray) and selector.ndim in (1, 2):
        custom = selector
        selector = None
    if custom is not None:
        custom = np.asarray(custom)
        if custom.ndim == 1:
            custom = custom[:, None]
        if custom.ndim != 2:
            raise ValueError("custom orbital coefficients must be a 1-D vector or 2-D column matrix")
        result = []
        for column in range(custom.shape[1]):
            name = "custom-orbital" if custom.shape[1] == 1 else f"custom-orbital-{column + 1}"
            values = _field_values(custom[:, column], ao_values, shape, name=name)
            result.append(
                ScalarField3D(
                    name=name,
                    label=name.replace("-", " ").title(),
                    kind="orbital",
                    values=values,
                    origin=origin,
                    axes=axes,
                    isovalues=isovalues,
                    opacity=opacity,
                    units="bohr^-3/2",
                    metadata={"source": "custom-coefficients", "column": column},
                )
            )
        return result

    if selector is None:
        return []
    spin_key = str(orbital_spin).lower()
    if len(coefficients) == 1:
        if spin_key not in {"auto", "restricted", "alpha", "both"}:
            raise ValueError("orbital_spin must be 'auto' for a restricted reference")
        spin_indices = (0,)
    else:
        if spin_key in {"auto", "both"}:
            spin_indices = (0, 1)
        elif spin_key in {"alpha", "a"}:
            spin_indices = (0,)
        elif spin_key in {"beta", "b"}:
            spin_indices = (1,)
        else:
            raise ValueError("orbital_spin must be 'auto', 'both', 'alpha', or 'beta'")

    result = []
    for spin_index in spin_indices:
        spin_name = ("alpha", "beta")[spin_index] if len(coefficients) == 2 else None
        matrix = np.asarray(coefficients[spin_index])
        if matrix.ndim != 2 or matrix.shape[0] != ao_values.shape[0]:
            raise ValueError("mo_coeff shape does not match the AO real-space dimension")
        occ = occupations[spin_index if len(occupations) == 2 else 0]
        for index, requested_label in _orbital_indices(selector, occ, matrix.shape[1]):
            base_name = f"mo-{index + 1}"
            name = f"{spin_name}-{base_name}" if spin_name else base_name
            label = f"{spin_name.title()} {requested_label}" if spin_name else requested_label
            energy = None
            if energies:
                energy_array = energies[spin_index if len(energies) == 2 else 0]
                energy = float(np.asarray(energy_array)[index])
                label += f"  E={energy:.6f} Eh"
            values = _field_values(matrix[:, index], ao_values, shape, name=name)
            result.append(
                ScalarField3D(
                    name=name,
                    label=label,
                    kind="orbital",
                    values=values,
                    origin=origin,
                    axes=axes,
                    isovalues=isovalues,
                    opacity=opacity,
                    units="bohr^-3/2",
                    metadata={
                        "orbital_index": index,
                        "spin": spin_name or "restricted",
                        "energy_hartree": energy,
                    },
                )
            )
    return result


def _default_density_matrices(reference) -> tuple[np.ndarray, ...]:
    maker = getattr(reference, "make_rdm1", None)
    if not callable(maker):
        raise TypeError("SCF object must provide make_rdm1() for density visualization")
    dm = np.asarray(maker())
    if dm.ndim == 2:
        return (dm,)
    if dm.ndim == 3 and dm.shape[0] == 2:
        return (dm[0], dm[1])
    raise ValueError("make_rdm1() must return (nao,nao) or (2,nao,nao)")


def _density_selection(reference, density) -> list[tuple[str, str, str, np.ndarray]]:
    defaults = None

    def default_matrices():
        nonlocal defaults
        if defaults is None:
            defaults = _default_density_matrices(reference)
        return defaults

    def named(key: str):
        matrices = default_matrices()
        unrestricted = len(matrices) == 2
        normalized = key.strip().lower().replace("_", "-")
        if normalized in {"electron", "total", "electron-density", "density"}:
            dm = matrices[0] if not unrestricted else matrices[0] + matrices[1]
            return ("electron-density", "Electron density", "electron-density", dm)
        if normalized in {"charge", "electronic-charge", "charge-density"}:
            dm = -(matrices[0] if not unrestricted else matrices[0] + matrices[1])
            return ("electronic-charge-density", "Electronic charge density", "difference-density", dm)
        if not unrestricted:
            raise ValueError(f"density={key!r} requires an unrestricted reference")
        if normalized in {"alpha", "alpha-density"}:
            return ("alpha-density", "Alpha density", "electron-density", matrices[0])
        if normalized in {"beta", "beta-density"}:
            return ("beta-density", "Beta density", "electron-density", matrices[1])
        if normalized in {"spin", "spin-density"}:
            return ("spin-density", "Spin density (alpha - beta)", "spin-density", matrices[0] - matrices[1])
        raise ValueError(f"unknown density selector {key!r}")

    if density is None or density is False:
        return []
    if density is True:
        return [named("electron")]
    if isinstance(density, str):
        if density.strip().lower() == "all":
            unrestricted = len(default_matrices()) == 2
            keys = ["electron", "alpha", "beta", "spin"] if unrestricted else ["electron"]
            return [named(key) for key in keys]
        return [named(density)]
    if isinstance(density, Mapping):
        result = []
        for key, matrix in density.items():
            name = str(key)
            normalized = name.lower().replace("_", "-")
            if "transition" in normalized:
                kind = "transition-density"
            elif "spin" in normalized:
                kind = "spin-density"
            else:
                kind = "difference-density"
            dm = np.asarray(matrix)
            result.append((name, name, kind, dm))
        return result
    if isinstance(density, (list, tuple)) and density and all(isinstance(item, str) for item in density):
        return [named(item) for item in density]

    array = np.asarray(density)
    if array.ndim == 2:
        return [("custom-density", "Custom density matrix", "difference-density", array)]
    if array.ndim == 3 and array.shape[0] == 2:
        alpha, beta = array
        return [
            ("electron-density", "Electron density", "electron-density", alpha + beta),
            ("alpha-density", "Alpha density", "electron-density", alpha),
            ("beta-density", "Beta density", "electron-density", beta),
            ("spin-density", "Spin density (alpha - beta)", "spin-density", alpha - beta),
        ]
    raise ValueError("density must be a selector, density matrix, spin pair, list, or mapping")


def _density_values(dm, ao_values, shape, *, name):
    dm = np.asarray(dm)
    if dm.shape != (ao_values.shape[0], ao_values.shape[0]):
        raise ValueError(
            f"density matrix {name!r} has shape {dm.shape}; expected "
            f"({ao_values.shape[0]}, {ao_values.shape[0]})"
        )
    values = np.einsum(
        "pg,pq,qg->g",
        ao_values.conj(),
        dm,
        ao_values,
        optimize=True,
    )
    return _real_array(values, name=name).reshape(shape)


def _density_fields(
    reference,
    density,
    *,
    ao_values,
    shape,
    origin,
    axes,
    isovalues,
    opacity,
) -> list[ScalarField3D]:
    result = []
    for name, label, kind, dm in _density_selection(reference, density):
        values = _density_values(dm, ao_values, shape, name=name)
        if kind == "difference-density" and np.min(values) >= -1.0e-12:
            kind = "electron-density"
        result.append(
            ScalarField3D(
                name=name,
                label=label,
                kind=kind,
                values=values,
                origin=origin,
                axes=axes,
                isovalues=isovalues,
                opacity=opacity,
                units="bohr^-3",
                metadata={"source": "density-matrix"},
            )
        )
    return result


def _total_dm(reference, supplied=None) -> np.ndarray:
    if supplied is not None and supplied is not True:
        array = np.asarray(supplied)
        if array.ndim == 3 and array.shape[0] == 2:
            return array[0] + array[1]
        if array.ndim == 2:
            return array
        raise ValueError("esp density matrix must have shape (nao,nao) or (2,nao,nao)")
    matrices = _default_density_matrices(reference)
    return matrices[0] if len(matrices) == 1 else matrices[0] + matrices[1]


def _density_requests_default_total(density) -> bool:
    if density is True:
        return True
    if isinstance(density, str):
        keys = [density]
    elif isinstance(density, (list, tuple)) and all(
        isinstance(item, str) for item in density
    ):
        keys = density
    else:
        return False
    normalized = {
        key.strip().lower().replace("_", "-")
        for key in keys
    }
    return bool(
        normalized
        & {"all", "electron", "total", "electron-density", "density"}
    )


def _nuclear_potential(molecule, points, spacing, *, regularize: bool) -> np.ndarray:
    coords = np.asarray(molecule.atom_coords(), dtype=float)
    charges_method = getattr(molecule, "atom_charges", None)
    if callable(charges_method):
        charges = np.asarray(charges_method(), dtype=float)
    else:
        charge_method = getattr(molecule, "atom_charge", None)
        if not callable(charge_method):
            raise TypeError("ESP requires atom_charges() or atom_charge(index)")
        charges = np.asarray([charge_method(i) for i in range(len(coords))], dtype=float)
    distances = np.linalg.norm(points[:, None, :] - coords[None, :, :], axis=2)
    if not regularize and np.any(distances < 1.0e-10):
        raise ValueError(
            "ESP grid contains a nucleus, where the point-charge potential diverges; "
            "use even grid dimensions or custom bounds"
        )
    cutoff = max(1.0e-10, 0.25 * float(np.min(spacing)))
    if regularize:
        distances = np.maximum(distances, cutoff)
    return np.sum(charges[None, :] / distances, axis=1)


def _pyscf_mep(reference, points, shape, spacing, dm):
    try:
        from pyscf import df, gto, lib
    except ImportError as exc:
        raise NotImplementedError("PySCF is not installed") from exc
    molecule = reference.mol
    pyscf_mol = molecule
    if not molecule.__class__.__module__.startswith("pyscf."):
        converter = getattr(molecule, "topyscf", None)
        if not callable(converter):
            raise NotImplementedError("molecule cannot be converted to PySCF")
        pyscf_mol = converter()
    density = np.asarray(dm)
    nao = int(pyscf_mol.nao_nr())
    if density.shape != (nao, nao):
        raise ValueError(
            f"density matrix shape {density.shape} does not match converted PySCF AO "
            f"dimension {nao}"
        )
    nuclear = _nuclear_potential(pyscf_mol, points, spacing, regularize=False)
    electron = np.empty(len(points), dtype=float)
    for start, stop in lib.prange(0, len(points), 600):
        fake = gto.fakemol_for_charges(points[start:stop])
        # ``fakemol_for_charges`` defaults to spherical.  Coulomb auxiliary
        # s functions are identical, but PySCF requires the representation
        # flag to match a Cartesian primary molecule.
        fake.cart = bool(getattr(pyscf_mol, "cart", False))
        integrals = df.incore.aux_e2(pyscf_mol, fake)
        electron[start:stop] = np.einsum(
            "ijp,ij->p", integrals, density, optimize=True
        ).real
    return _real_array(
        nuclear - electron,
        name="electrostatic potential",
    ).reshape(shape)


def _fft_mep(molecule, points, shape, spacing, density_values):
    try:
        from scipy.signal import fftconvolve
    except ImportError as exc:  # pragma: no cover - SciPy is a core dependency
        raise ImportError("approximate ESP visualization requires scipy") from exc
    offsets = [np.arange(-(size - 1), size, dtype=float) * step for size, step in zip(shape, spacing)]
    rx, ry, rz = np.meshgrid(*offsets, indexing="ij")
    radius = np.sqrt(rx * rx + ry * ry + rz * rz)
    kernel = np.zeros_like(radius)
    np.divide(1.0, radius, out=kernel, where=radius > 0.0)
    voxel = float(np.prod(spacing))
    electron = fftconvolve(density_values, kernel, mode="same") * voxel
    nuclear = _nuclear_potential(
        molecule,
        points,
        spacing,
        regularize=True,
    ).reshape(shape)
    return nuclear - electron


def _esp_fields(
    reference,
    esp,
    *,
    method,
    cube,
    points,
    ao_values,
    shape,
    origin,
    axes,
    density_fields,
    reuse_density_surface,
    isovalues,
    opacity,
) -> list[ScalarField3D]:
    if esp is None or esp is False:
        return []
    dm = _total_dm(reference, supplied=esp)
    density_surface = (
        next(
            (item for item in density_fields if item.name == "electron-density"),
            None,
        )
        if reuse_density_surface
        else None
    )
    additions = []
    if density_surface is None:
        surface_name = "electron-density" if not density_fields else "esp-surface-density"
        density_surface = ScalarField3D(
            name=surface_name,
            label="Electron density (ESP surface)",
            kind="electron-density",
            values=_density_values(dm, ao_values, shape, name=surface_name),
            origin=origin,
            axes=axes,
            isovalues=None,
            opacity=0.55,
            units="bohr^-3",
            metadata={"source": "density-matrix"},
        )
        additions.append(density_surface)

    method_key = str(method).lower()
    if method_key not in {"auto", "exact", "fft"}:
        raise ValueError("esp_method must be 'auto', 'exact', or 'fft'")
    exact_error = None
    if method_key in {"auto", "exact"}:
        try:
            values = _pyscf_mep(
                reference,
                points,
                shape,
                np.asarray(cube.spacing, dtype=float),
                dm,
            )
            metadata = {
                "method": "pyscf-exact",
                "approximate": False,
                "units": "hartree/e",
            }
        except Exception as exc:
            exact_error = exc
            if method_key == "exact":
                raise RuntimeError("exact PySCF ESP evaluation failed") from exc
        else:
            return additions + [
                ScalarField3D(
                    name="esp",
                    label="Electrostatic potential",
                    kind="esp",
                    values=values,
                    origin=origin,
                    axes=axes,
                    isovalues=isovalues,
                    opacity=opacity,
                    units="hartree/e",
                    surface_field=density_surface.name,
                    metadata=metadata,
                )
            ]

    values = _fft_mep(
        reference.mol,
        points,
        shape,
        np.asarray(cube.spacing, dtype=float),
        density_surface.values,
    )
    metadata = {
        "method": "fft-convolution",
        "approximate": True,
        "units": "hartree/e",
    }
    if exact_error is not None:
        # Keep the public schema deliberately stable; the exception remains
        # available through exact mode instead of being serialized to a page.
        pass
    return additions + [
        ScalarField3D(
            name="esp",
            label="Electrostatic potential (FFT approximation)",
            kind="esp",
            values=values,
            origin=origin,
            axes=axes,
            isovalues=isovalues,
            opacity=opacity,
            units="hartree/e",
            surface_field=density_surface.name,
            metadata=metadata,
        )
    ]


def _state_count(td) -> int:
    for attribute in ("e", "energies", "e_tot"):
        value = getattr(td, attribute, None)
        if value is not None:
            array = np.asarray(value)
            if array.ndim == 1 and array.size:
                return int(array.size)
    ci = getattr(td, "ci", None)
    if isinstance(ci, (list, tuple)):
        return len(ci)
    xy = getattr(td, "xy", None)
    if isinstance(xy, (list, tuple)):
        return len(xy)
    array = np.asarray(xy) if xy is not None else None
    if array is not None and array.ndim >= 2:
        return int(array.shape[-1])
    x = getattr(td, "x", None)
    if x is not None and np.asarray(x).ndim == 3:
        return int(np.asarray(x).shape[-1])
    for attribute in ("tdm", "tdm1", "transition_density_matrix", "transition_density"):
        value = getattr(td, attribute, None)
        if value is not None and not callable(value):
            array = np.asarray(value)
            if array.ndim == 3:
                return int(array.shape[0])
    raise ValueError("cannot infer the number of excited states; use an explicit state index")


def _state_indices(selector, td) -> list[int]:
    if selector is True:
        requested = [0]
    elif isinstance(selector, str):
        if selector.strip().lower() != "all":
            raise ValueError("nto must be a state index, list of indices, or 'all'")
        requested = list(range(_state_count(td)))
    elif np.isscalar(selector):
        requested = [int(selector)]
    else:
        requested = [int(value) for value in selector]
    if not requested:
        raise ValueError("NTO state list cannot be empty")
    if any(index < 0 for index in requested):
        raise IndexError("NTO state indices must be non-negative")
    count = None
    try:
        count = _state_count(td)
    except ValueError:
        pass
    if count is not None and any(index >= count for index in requested):
        raise IndexError(f"NTO state index is outside [0, {count})")
    return requested


def _xy_item(td, state, nocc, nvir) -> tuple[np.ndarray, np.ndarray]:
    dimension = nocc * nvir
    ci = getattr(td, "ci", None)
    converter = getattr(td, "vec_to_amplitudes", None)
    if isinstance(ci, (list, tuple)) and callable(converter):
        return np.asarray(converter(ci[state])), np.zeros((nocc, nvir))

    x_attr = getattr(td, "x", getattr(td, "X", None))
    if x_attr is not None:
        x = np.asarray(x_attr)
        if x.shape[:2] == (nocc, nvir) and x.ndim == 3:
            return x[:, :, state], np.zeros((nocc, nvir))
        if x.shape == (nocc, nvir):
            if state != 0:
                raise IndexError("only one transition amplitude is available")
            return x, np.zeros_like(x)

    xy = getattr(td, "xy", None)
    if isinstance(xy, (list, tuple)):
        item = xy[state]
        if isinstance(item, (list, tuple)) and len(item) == 2:
            x, y = item
            x = np.asarray(x)
            y = np.zeros_like(x) if np.isscalar(y) else np.asarray(y)
            return x.reshape(nocc, nvir), y.reshape(nocc, nvir)
        return np.asarray(item).reshape(nocc, nvir), np.zeros((nocc, nvir))
    if xy is not None:
        array = np.asarray(xy)
        if td.__class__.__module__ == "pyqed.qchem.tdscf.tdhf":
            raise NotImplementedError(
                "legacy native TDHF stores Casida eigenvectors rather than physical "
                "X/Y amplitudes; automatic NTO extraction is unavailable for this object"
            )
        if array.ndim == 2 and array.shape[0] == dimension:
            return array[:, state].reshape(nocc, nvir), np.zeros((nocc, nvir))
        if array.ndim == 2 and array.shape[0] == 2 * dimension:
            vector = array[:, state]
            return (
                vector[:dimension].reshape(nocc, nvir),
                vector[dimension:].reshape(nocc, nvir),
            )
        if array.shape == (nocc, nvir):
            return array, np.zeros_like(array)

    amplitudes = getattr(td, "amplitudes", None)
    if amplitudes is not None:
        array = np.asarray(amplitudes)
        item = array[state] if array.ndim == 3 else array
        return item.reshape(nocc, nvir), np.zeros((nocc, nvir))

    tdm = next(
        (
            candidate
            for candidate in (
                getattr(td, "tdm", None),
                getattr(td, "transition_density_matrix", None),
                getattr(td, "transition_density", None),
                getattr(td, "get_tdm", None),
            )
            if callable(candidate)
        ),
        None,
    )
    if tdm is not None:
        try:
            value = tdm(state, representation="mo")
        except TypeError:
            try:
                value = tdm(state)
            except TypeError:
                try:
                    value = tdm(state + 1, 0)
                except TypeError:
                    if state != 0:
                        raise
                    value = tdm()
        array = np.asarray(value)
        if array.shape == (nocc, nvir):
            return array, np.zeros_like(array)
        if array.ndim == 2 and array.shape[0] >= nocc and array.shape[1] >= nocc + nvir:
            return array[:nocc, nocc:nocc + nvir], np.zeros((nocc, nvir))
    for attribute in ("tdm", "tdm1", "transition_density_matrix", "transition_density"):
        value = getattr(td, attribute, None)
        if value is None or callable(value):
            continue
        array = np.asarray(value)
        if array.ndim == 3:
            array = array[state]
        elif state != 0:
            continue
        if array.shape == (nocc, nvir):
            return array, np.zeros_like(array)
        if array.ndim == 2 and array.shape[0] >= nocc and array.shape[1] >= nocc + nvir:
            return array[:nocc, nocc:nocc + nvir], np.zeros((nocc, nvir))
    raise TypeError("TD object exposes neither usable amplitudes nor a transition density matrix")


def _nto_fields(
    td,
    selector,
    *,
    reference,
    pairs,
    method,
    ao_values,
    shape,
    origin,
    axes,
    isovalues,
    opacity,
) -> list[ScalarField3D]:
    coeffs = _spin_arrays(reference, "mo_coeff")
    occs = _spin_arrays(reference, "mo_occ")
    if len(coeffs) != 1 or len(occs) != 1:
        raise NotImplementedError("automatic NTO extraction currently requires a restricted reference")
    mo_coeff = np.asarray(coeffs[0])
    mo_occ = np.asarray(occs[0])
    occ_idx = np.flatnonzero(mo_occ > 1.0e-8)
    vir_idx = np.flatnonzero(mo_occ <= 1.0e-8)
    if not len(occ_idx) or not len(vir_idx):
        raise ValueError("NTOs require occupied and virtual orbitals")
    npairs = int(pairs)
    if npairs < 1:
        raise ValueError("nto_pairs must be positive")
    method_key = str(method).lower()
    if method_key not in {"x", "transition"}:
        raise ValueError("nto_method must be 'x' or 'transition'")

    result = []
    for state in _state_indices(selector, td):
        x, y = _xy_item(td, state, len(occ_idx), len(vir_idx))
        if x.shape != (len(occ_idx), len(vir_idx)) or y.shape != x.shape:
            raise ValueError("transition amplitudes do not match occupied/virtual dimensions")
        amplitude = x if method_key == "x" else x + y
        hole_rotation, singular_values, particle_h = np.linalg.svd(amplitude, full_matrices=False)
        total = float(np.sum(singular_values**2))
        if total <= np.finfo(float).eps:
            raise ValueError(f"state {state} has a zero transition amplitude")
        particle_rotation = particle_h.conj().T
        for pair in range(min(npairs, len(singular_values))):
            weight = float(singular_values[pair] ** 2 / total)
            hole_coeff = mo_coeff[:, occ_idx] @ hole_rotation[:, pair]
            particle_coeff = mo_coeff[:, vir_idx] @ particle_rotation[:, pair]
            prefix = f"state-{state + 1}-nto-{pair + 1}"
            common = {
                "state_index": state,
                "pair_index": pair,
                "weight": weight,
                "method": method_key,
            }
            result.extend(
                [
                    ScalarField3D(
                        name=f"{prefix}-hole",
                        label=f"State {state + 1} NTO {pair + 1} hole ({weight:.1%})",
                        kind="orbital",
                        values=_field_values(hole_coeff, ao_values, shape, name="NTO hole"),
                        origin=origin,
                        axes=axes,
                        isovalues=isovalues,
                        opacity=opacity,
                        units="bohr^-3/2",
                        metadata={**common, "role": "hole"},
                    ),
                    ScalarField3D(
                        name=f"{prefix}-particle",
                        label=f"State {state + 1} NTO {pair + 1} particle ({weight:.1%})",
                        kind="orbital",
                        values=_field_values(particle_coeff, ao_values, shape, name="NTO particle"),
                        origin=origin,
                        axes=axes,
                        isovalues=isovalues,
                        opacity=opacity,
                        units="bohr^-3/2",
                        metadata={**common, "role": "particle"},
                    ),
                ]
            )
    return result


