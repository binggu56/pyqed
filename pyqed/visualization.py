def _safe_field_name(value: str, fallback: str) -> str:
    cleaned = re.sub(r"[^a-z0-9]+", "-", value.lower()).strip("-")
    return (cleaned or fallback)[:80]


def _read_cube(path: Path, *, dataset: int | str = 0):
    """Read the core Gaussian-cube subset without requiring optional ASE."""
    if path.stat().st_size > _MAX_CUBE_BYTES:
        raise ValueError(
            f"cube file is larger than the {_MAX_CUBE_BYTES:,}-byte input limit"
        )
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except UnicodeDecodeError as exc:
        raise ValueError(f"cube file {path} is not UTF-8 text") from exc
    if len(lines) < 6:
        raise ValueError("cube file is too short")
    comment = lines[0].strip() or path.stem
    description = " ".join(line.strip() for line in lines[:2] if line.strip())
    atom_line = lines[2].split()
    if len(atom_line) < 4:
        raise ValueError("invalid cube origin line")
    signed_natoms = int(atom_line[0])
    natoms = abs(signed_natoms)
    origin = np.asarray([float(value.replace("D", "E")) for value in atom_line[1:4]])
    nval = int(atom_line[4]) if len(atom_line) >= 5 else 1
    shapes = []
    axes = []
    count_signs = []
    for line in lines[3:6]:
        values = line.split()
        if len(values) < 4:
            raise ValueError("invalid cube axis line")
        count = int(values[0])
        count_signs.append(np.sign(count))
        shapes.append(abs(count))
        axes.append([float(value.replace("D", "E")) for value in values[1:4]])
    if any(size < 2 for size in shapes):
        raise ValueError("cube grid dimensions must each be at least 2")
    if any(sign == 0 for sign in count_signs) or len(set(count_signs)) != 1:
        raise ValueError("cube grid counts must be consistently positive or negative")
    # Gaussian's convention is positive counts in Bohr and negative in Angstrom.
    length_scale = au2angstrom if count_signs[0] > 0 else 1.0
    origin *= length_scale
    axes = np.asarray(axes, dtype=float) * length_scale

    cursor = 6
    numbers = []
    positions = []
    for _ in range(natoms):
        values = lines[cursor].split()
        cursor += 1
        if len(values) < 5:
            raise ValueError("invalid cube atom line")
        numbers.append(int(float(values[0])))
        positions.append([float(value.replace("D", "E")) * length_scale for value in values[2:5]])
    if signed_natoms < 0:
        labels = []
        while cursor < len(lines) and not labels:
            row = lines[cursor].split()
            cursor += 1
            if row:
                count = int(row[0])
                labels.extend(row[1:])
                while len(labels) < count and cursor < len(lines):
                    labels.extend(lines[cursor].split())
                    cursor += 1
                labels = labels[:count]
        if labels:
            nval = len(labels)
    if isinstance(dataset, str):
        if dataset.strip().lower() != "all":
            raise ValueError("cube dataset must be an integer index or 'all'")
        selected = list(range(nval))
    else:
        index = int(dataset)
        if index != dataset:
            raise TypeError("cube dataset indices must be integers")
        if index < 0 or index >= nval:
            raise IndexError(f"cube dataset {index} is outside [0, {nval})")
        selected = [index]
    raw = []
    for line in lines[cursor:]:
        raw.extend(float(value.replace("D", "E")) for value in line.split())
    expected = int(np.prod(shapes)) * nval
    if len(raw) != expected:
        raise ValueError(f"cube contains {len(raw)} values; expected {expected}")
    array = np.asarray(raw, dtype=float).reshape((-1, nval), order="C")
    symbols = [
        _ELEMENT_SYMBOLS[number] if 0 < number < len(_ELEMENT_SYMBOLS) else "X"
        for number in numbers
    ]
    if any(symbol == "X" for symbol in symbols):
        raise ValueError("cube contains an unsupported atomic number")
    xyz = _xyz_from_arrays(symbols, np.asarray(positions, dtype=float))
    lowered = description.lower()
    if nval > 1 or "orbital" in lowered:
        kind = "orbital"
    elif "spin" in lowered:
        kind = "spin-density"
    elif "electrostatic" in lowered or "potential" in lowered or "mep" in lowered:
        kind = "esp"
    elif "density" in lowered:
        kind = "electron-density"
    else:
        kind = "generic"
    fields = []
    for index in selected:
        dataset_label = labels[index] if signed_natoms < 0 and labels else str(index + 1)
        name = _safe_field_name(
            path.stem if nval == 1 else f"{path.stem}-{dataset_label}",
            f"cube-field-{index + 1}",
        )
        label = comment if nval == 1 else f"Orbital {dataset_label}"
        fields.append(
            ScalarField3D(
                name=name,
                label=label[:120],
                kind=kind,
                values=array[:, index].reshape(tuple(shapes), order="C"),
                origin=origin,
                axes=axes,
                units=None,
                metadata={"source": "cube", "dataset": index},
            )
        )
    return xyz, tuple(fields)


def view(
    obj,
    *,
    mode: int | None = None,
    amplitude: str | float = "auto",
    frames: int = 24,
    interval: int = 30,
    orbital=None,
    coeff=None,
    orbital_spin: str = "auto",
    density=None,
    esp=False,
    esp_method: str = "auto",
    nto=None,
    nto_pairs: int = 1,
    nto_method: str = "x",
    fields: ScalarField3D | Iterable[ScalarField3D] | None = None,
    active_field: str | int | None = None,
    dataset: int | str = 0,
    nx: int = 40,
    ny: int | None = None,
    nz: int | None = None,
    margin: float = 3.0,
    bounds=None,
    isovalues=None,
    opacity: float = 0.72,
    title: str | None = None,
    representation: str = "ball-stick",
    labels: bool = False,
    width: int = 900,
    height: int = 640,
    coordinates_unit: str = "bohr",
    open_browser: bool | None = None,
) -> SceneView:
    """Build an interactive molecular/volumetric scene.

    Examples
    --------
    ``view(mol)`` shows geometry and ``view(hessian, mode=0)`` animates one
    harmonic normal mode.  For a converged SCF object, use
    ``view(mf, orbital=['homo', 'lumo'])``, ``orbital='all'``,
    ``density='all'`` (including unrestricted spin density), or ``esp=True``.
    ``view(td, nto='all')`` builds NTO hole/particle layers for every exposed
    excited-state amplitude.  A Gaussian cube path is accepted directly.

    Coordinates in generated grids are sampled in Bohr and transported to the
    browser in Angstrom.  Scalar values retain their documented atomic units.
    Volumetric data is never encoded in a URL fragment.
    """
    esp_requested = esp is not None and esp is not False
    density_requested = density is not None and density is not False
    nto_requested = nto is not None and nto is not False
    mode_requested = mode is not None
    if mode_requested and (
        orbital is not None
        or coeff is not None
        or density_requested
        or nto_requested
        or fields is not None
        or esp_requested
    ):
        raise ValueError("normal-mode animation cannot be combined with scalar fields")
    if isinstance(obj, SceneView):
        if (
            mode_requested
            or amplitude != "auto"
            or orbital is not None
            or coeff is not None
            or density_requested
            or nto_requested
            or fields is not None
            or esp_requested
        ):
            raise ValueError("cannot add computed fields when obj is already a SceneView")
        result = obj
    elif isinstance(obj, (str, Path)):
        path = Path(obj).expanduser()
        if not path.is_file():
            raise FileNotFoundError(path)
        if path.suffix.lower() not in {".cube", ".cub"}:
            raise ValueError("view(path) currently accepts .cube and .cub files")
        if (
            mode_requested
            or amplitude != "auto"
            or orbital is not None
            or coeff is not None
            or density_requested
            or nto_requested
            or fields is not None
            or esp_requested
        ):
            raise ValueError("computed field options cannot be combined with a cube path")
        xyz, cube_fields = _read_cube(path, dataset=dataset)
        result = VolumeView(
            xyz=xyz,
            fields=cube_fields,
            representation=representation,
            labels=bool(labels),
            width=width,
            height=height,
            title=title or cube_fields[0].label,
            active_field=active_field,
        )
    else:
        molecule = _molecule_from_object(obj)
        xyz = _molecule_xyz(molecule, coordinates_unit=coordinates_unit)
        vibration = None
        if mode_requested:
            vibration = _normal_mode_animation(
                obj,
                molecule,
                mode=mode,
                amplitude=amplitude,
                coordinates_unit=coordinates_unit,
                frames=frames,
                interval=interval,
            )
        external_fields: list[ScalarField3D] = []
        if fields is not None:
            if isinstance(fields, ScalarField3D):
                external_fields = [fields]
            else:
                external_fields = list(fields)

        needs_computed = (
            orbital is not None
            or coeff is not None
            or density_requested
            or nto_requested
            or esp_requested
        )
        computed: list[ScalarField3D] = []
        if needs_computed:
            reference = _scf_reference(obj)
            if reference is None:
                raise TypeError("orbital, density, ESP, and NTO views require an SCF reference")
            cube = _grid(
                molecule,
                nx=nx,
                ny=ny,
                nz=nz,
                margin=margin,
                bounds=bounds,
            )
            points, origin, axes = _grid_geometry(cube)
            shape = (cube.nx, cube.ny, cube.nz)
            ao_values = _evaluate_ao(reference, points)
            computed.extend(
                _orbital_fields(
                    reference,
                    orbital,
                    coeff=coeff,
                    orbital_spin=orbital_spin,
                    ao_values=ao_values,
                    shape=shape,
                    origin=origin,
                    axes=axes,
                    isovalues=isovalues,
                    opacity=opacity,
                )
            )
            density_result = _density_fields(
                reference,
                density,
                ao_values=ao_values,
                shape=shape,
                origin=origin,
                axes=axes,
                isovalues=isovalues,
                opacity=opacity,
            )
            computed.extend(density_result)
            computed.extend(
                _esp_fields(
                    reference,
                    esp,
                    method=esp_method,
                    cube=cube,
                    points=points,
                    ao_values=ao_values,
                    shape=shape,
                    origin=origin,
                    axes=axes,
                    density_fields=density_result,
                    reuse_density_surface=(
                        esp is True and _density_requests_default_total(density)
                    ),
                    isovalues=isovalues,
                    opacity=opacity,
                )
            )
            if nto_requested:
                computed.extend(
                    _nto_fields(
                        obj,
                        nto,
                        reference=reference,
                        pairs=nto_pairs,
                        method=nto_method,
                        ao_values=ao_values,
                        shape=shape,
                        origin=origin,
                        axes=axes,
                        isovalues=isovalues,
                        opacity=opacity,
                    )
                )

        all_fields = tuple(external_fields + computed)
        cls = VolumeView if all_fields else SceneView
        result = cls(
            xyz=xyz,
            fields=all_fields,
            representation=representation,
            labels=bool(labels),
            width=width,
            height=height,
            title=title or (vibration.label if vibration is not None else None),
            active_field=active_field,
            vibration=vibration,
        )

    should_open = not _in_notebook() if open_browser is None else bool(open_browser)
    if should_open:
        result.open()
    return result


